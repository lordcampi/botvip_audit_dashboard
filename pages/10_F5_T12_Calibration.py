DATA_DIR = os.path.join(os.path.dirname(os.path.dirname(__file__)), "data")


def load_json(filename: str) -> Optional[Dict[str, Any]]:
    """Load a JSON file from data/ directory."""
    path = os.path.join(DATA_DIR, filename)
    if not os.path.exists(path):
        return None
    try:
        with open(path) as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        st.error(f"Error loading {filename}: {e}")
        return None


def color_decision(val: Any) -> str:
    """Return a CSS background color for a decision value."""
    if val is None or val == "N/A":
        return ""
    s = str(val).upper()
    if "KEEP" in s or "ALLOW" in s or "PROMOTE" in s or "EXPAND" in s:
        return "background-color: #d4edda; color: #155724"  # green
    if "RESTRICT" in s or "BLOCK" in s or "REMOVE" in s:
        return "background-color: #f8d7da; color: #721c24"  # red
    if "WATCH" in s or "REVIEW" in s or "CONTEXTUAL" in s:
        return "background-color: #fff3cd; color: #856404"  # yellow
    if "INSUFFICIENT" in s or "SAMPLE" in s:
        return "background-color: #e2e3e5; color: #383d41"  # gray
    return ""


def highlight_decision(val: Any) -> str:
    """Return CSS for decision column cells."""
    return color_decision(val)


def fmt(val: Any, decimals: int = 4) -> str:
    """Format a numeric value, returning 'N/A' for None."""
    if val is None or val == "N/A":
        return "N/A"
    try:
        f = float(val)
        if abs(f) >= 10000:
            return f"{f:,.2f}"
        return f"{f:.{decimals}f}"
    except (ValueError, TypeError):
        return str(val)


def fmt_pct(val: Any) -> str:
    """Format as percentage."""
    if val is None:
        return "N/A"
    try:
        return f"{float(val) * 100:.2f}%"
    except (ValueError, TypeError):
        return str(val)


def safe_int(val: Any) -> str:
    """Format as integer or N/A."""
    if val is None:
        return "N/A"
    try:
        return str(int(val))
    except (ValueError, TypeError):
        return str(val)


