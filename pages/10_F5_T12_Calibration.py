def main():
    # Check if data files exist
    files_exist = all(
        os.path.exists(os.path.join(DATA_DIR, f))
        for f in ["01_pf_decomposition_compact.json", "02_no_progress_compact.json",
                  "03_filter_contribution_matrix.json", "04_symbol_calibration_table.json",
                  "05_managed_exit_damage_table.json", "06_candidate_promotion_table.json"]
    )
    
    if not files_exist:
        st.warning(
            "⚠️ Some F5_T12 data files are missing. "
            "Run the batch generators first:\n\n"
            "```bash\n"
            "python src/f5_t12_generate_pf_decomposition.py\n"
            "python src/f5_t12_generate_no_progress_compact.py\n"
            "python src/f5_t12_generate_managed_exit_damage.py\n"
            "python src/f5_t12_generate_filter_contribution.py\n"
            "python src/f5_t12_generate_symbol_calibration.py\n"
            "python src/f5_t12_generate_candidate_promotion.py\n"
            "```"
        )
        return
    
    # Last generation time
    timestamps = []
    for f in ["01_pf_decomposition_compact.json", "02_no_progress_compact.json",
              "03_filter_contribution_matrix.json", "04_symbol_calibration_table.json",
              "05_managed_exit_damage_table.json", "06_candidate_promotion_table.json"]:
        path = os.path.join(DATA_DIR, f)
        if os.path.exists(path):
            timestamps.append(os.path.getmtime(path))
    if timestamps:
        latest = datetime.fromtimestamp(max(timestamps))
        st.caption(f"🕐 Data last updated: {latest.strftime('%Y-%m-%d %H:%M:%S')}")
    
    # Render panels
    render_pf_overview()
    st.divider()
    
    tab1, tab2, tab3, tab4, tab5, tab6 = st.tabs([
        "📋 PF Decomposition",
        "⏳ No-Progress",
        "🚪 Managed Exits",
        "🔍 Filter Matrix",
        "💱 Symbols",
        "🏆 Candidates",
    ])
    
    with tab1:
        render_pf_decomposition()
    
    with tab2:
        render_no_progress()
    
    with tab3:
        render_managed_exit_damage()
    
    with tab4:
        render_filter_contribution()
    
    with tab5:
        render_symbol_calibration()
    
    with tab6:
        render_candidate_promotion()
    
    # Footer with batch info
    st.divider()
    st.caption(
        "F5_T12 — Calibration Cockpit | Batches 2-7 generate JSON, Batch 8 renders. "
        "No TP/SL/lifecycle/schema modified. "
        "Killzone replaced by session_bucket + weekend."
    )


if __name__ == "__main__":
    main()
