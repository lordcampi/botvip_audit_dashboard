def render_pf_decomposition():
    """Render the PF Decomposition table."""
    st.subheader("📋 PF Decomposition")
    st.caption("Profit Factor broken down by dimension and segment.")
    
    data = load_json("01_pf_decomposition_compact.json")
    if data is None:
        st.warning("Data not found.")
        return
    
    rows = data.get("rows", [])
    if not rows:
        st.info("No data.")
        return
    
    df = pd.DataFrame(rows)
    
    # Select and order columns
    cols = ["dimension", "segment", "count", "r_values_count", "wins", "losses",
            "gross_win_r", "gross_loss_abs_r", "net_r", "avg_r",
            "avg_win_r", "avg_loss_r", "profit_factor", "decision"]
    display_cols = [c for c in cols if c in df.columns]
    
    df_display = df[display_cols].copy()
    
    # Format numeric columns
    for c in ["gross_win_r", "gross_loss_abs_r", "net_r", "avg_r", "avg_win_r", "avg_loss_r", "profit_factor"]:
        if c in df_display.columns:
            df_display[c] = df_display[c].apply(fmt)
    
    # Color decision column
    styled = df_display.style.apply(highlight_decision, subset=["decision"] if "decision" in df_display.columns else [])
    
    st.dataframe(styled, use_container_width=True, height=min(400, 35 * len(df_display) + 35))
    
    # Summary stats
    decisions = df["decision"].value_counts().to_dict() if "decision" in df.columns else {}
    if decisions:
        st.caption(f"Decisions: {', '.join(f'**{k}**: {v}' for k, v in decisions.items())}")


