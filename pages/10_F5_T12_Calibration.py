def render_pf_overview():
    """Render PF Overview metrics from the decomposition table."""
    st.subheader("📊 PF Overview")
    
    data = load_json("01_pf_decomposition_compact.json")
    if data is None:
        st.warning("PF decomposition data not found. Run Batch 2 first.")
        return
    
    rows = data.get("rows", [])
    if not rows:
        st.info("No PF decomposition data available.")
        return
    
    # Find ALL, directional, managed rows
    all_row = next((r for r in rows if r.get("dimension") == "ALL" and r.get("segment") == "ALL"), None)
    dir_row = next((r for r in rows if r.get("dimension") == "exit_family" and r.get("segment") == "directional"), None)
    mgd_row = next((r for r in rows if r.get("dimension") == "exit_family" and r.get("segment") == "managed"), None)
    
    meta = data.get("meta", {})
    col1, col2, col3, col4, col5 = st.columns(5)
    
    with col1:
        st.metric("Total Signals", meta.get("total_signal_records", "?"))
    
    with col2:
        if all_row:
            pf = all_row.get("profit_factor")
            st.metric("PF Total", fmt(pf, 4) if pf is not None else "∞ (no losses)")
        else:
            st.metric("PF Total", "N/A")
    
    with col3:
        if dir_row:
            pf = dir_row.get("profit_factor")
            st.metric("PF Directional", fmt(pf, 4) if pf is not None else "∞ (no losses)")
        else:
            st.metric("PF Directional", "N/A")
    
    with col4:
        if mgd_row:
            pf = mgd_row.get("profit_factor")
            st.metric("PF Managed", fmt(pf, 4) if pf is not None else "∞ (no losses)")
        else:
            st.metric("PF Managed", "N/A")
    
    with col5:
        if all_row:
            net_r = all_row.get("net_r")
            st.metric("Net R Total", fmt(net_r, 2) if net_r is not None else "N/A")
        else:
            st.metric("Net R Total", "N/A")
    
    # Quick summary
    if all_row:
        st.caption(
            f"Wins: {all_row.get('wins', '?')} | Losses: {all_row.get('losses', '?')} | "
            f"Gross Win R: {fmt(all_row.get('gross_win_r'))} | "
            f"Gross Loss R: {fmt(all_row.get('gross_loss_abs_r'))} | "
            f"Decision: **{all_row.get('decision', '?')}**"
        )


